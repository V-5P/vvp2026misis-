group_stats = df.groupby(['Pclass', 'Sex']).agg(Количество=('PassengerId', 'count'), Средний_возраст=('Age', 'mean'), Доля_выживших=('Survived', 'mean'), Средняя_стоимость=('Fare', 'mean'))
print(group_stats)
